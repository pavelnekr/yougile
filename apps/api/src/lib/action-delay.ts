// Единая пауза между действиями в YouGile.
//
// Каждая фоновая операция (назначение, снятие, отправка комментариев) и проверка
// работ выполняет запросы к YouGile строго по очереди, с паузой 4 секунды перед
// следующим действием. 4 секунды выбраны после того, как YouGile начал отвечать
// HTTP 429 «Too Many Requests» на части площадок в «Проверке работ»: паузы в
// 2 секунды хватало на тестовой среде, а на проде скорости не хватало. Пауза —
// компромисс между скоростью операции и консистентностью YouGile: за это время
// предыдущая запись успевает примениться, следующий запрос не «догоняет» её в
// очереди трекера, а YouGile не получает пачку запросов разом.
//
// Один и тот же тайминг во всех местах — осознанно: если паузу где-то изменить,
// порядок и темп операций разъедутся, и оператор не сможет объяснить, почему
// комментарии летят быстрее назначений.
export const yougileActionDelayMs = 4_000;

export function delayBetweenYougileActions(): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, yougileActionDelayMs));
}