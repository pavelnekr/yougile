// Разметка шаблонов комментариев: `**слово**` выделяет слово жирным в чате YouGile.
//
// YouGile принимает в чат два поля: `text` (простой текст) и `textHtml` (HTML),
// и показывает форматирование по HTML — так же, как уже делает комментарий
// кластера (clusterMessage в assignments/service.ts). Поэтому шаблон хранится
// и сохраняется как есть, а конвертация происходит в момент отправки:
// звёздочки уходят в `text` вырезанными (в пушике и в копии сообщения будет
// чистый текст), а жирный — в `textHtml`.

/** Есть ли в тексте парная разметка `**слово**`. `[\s\S]` — внутри может быть
 *  и перевод строки (выделяется целое предложение из нескольких строк). */
const markupPattern = /\*\*[\s\S]+\*\*/;

/** `**слово**` → `слово` для версии сообщения без форматирования.
 *  Ленивое согласование: пара ищется до ближайших `**`, одиночная звёздочка
 *  внутри выделения допускается. */
const markupGlobalPattern = /\*\*([\s\S]+?)\*\*/g;

function escapeHtml(value: string): string {
  return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

export type YougileCommentMessage = {
  /** Текст без разметки: уходит в поле `text` запроса. */
  text: string;
  /** HTML-версия с `<b>`; есть только когда разметка реально использована,
   *  чтобы шаблоны без `**` отправлялись тем же запросом, что и раньше. */
  textHtml?: string;
};

/**
 * Сообщение чата YouGile из текста комментария. Без `**...**` возвращает
 * исходный текст без HTML-версии; с разметкой — текст с вырезанными звёздочками
 * и HTML, где `**слово**` стало `<b>слово</b>`, строки — абзацами `<p>`.
 *
 * Строки без парных звёздочек (незакрытая `**`) остаются как есть — разметка
 * не угадывает намерения и не ломает текст.
 */
export function renderCommentForYougile(comment: string): YougileCommentMessage {
  if (!markupPattern.test(comment)) return { text: comment };

  // `<b>` может пересекать перевод строки, поэтому строки в абзацы не режутся:
  // разорванный между `<p>` тег сломал бы разметку сообщения. Вместо этого
  // один `<p>` с `<br/>` — переносы строк сохраняются и внутри выделения.
  const html = escapeHtml(comment).replace(markupGlobalPattern, "<b>$1</b>");
  const textHtml = `<p>${html.replace(/\r?\n/g, "<br/>")}</p>`;

  return {
    text: comment.replace(markupGlobalPattern, "$1"),
    textHtml
  };
}
