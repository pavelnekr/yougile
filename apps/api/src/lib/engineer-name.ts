// Единая нормализация имён инженеров для сравнения.
//
// Любое сопоставление имени из XLSX с именем в YouGile идёт через
// normalizeEngineerName: NFKC, trim, схлопывание пробелов, lower-case для ru.
//
// Кроме того, слова сортируются по алфавиту — «Иван Иванов» и «Иванов Иван»
// считаются одним именем. В планах XLSX порядок «имя фамилия» и «фамилия имя»
// встречается вперемешку, а строгое сравнение давало ложные ENGINEER_NOT_FOUND
// и ошибки «имя изменилось в YouGile». Сортировка безопасна для многословных
// имён: разный набор слов не совпадёт, а одинаковый набор в любом порядке — да.
export function normalizeEngineerName(name: string) {
  return name
    .normalize("NFKC")
    .trim()
    .replace(/\s+/g, " ")
    .toLocaleLowerCase("ru")
    .split(" ")
    .sort()
    .join(" ");
}